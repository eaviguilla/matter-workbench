"""Write clio_filler/forms-data.js from app/forms.py, so the Chrome extension and the app never disagree about the
questions. Run it after any change to a form in app/forms.py. tests/test_clio_filler.py fails when the file is stale.

    python scripts/build_clio_forms.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from app import forms, outputs  # noqa: E402

TARGET = ROOT / "clio_filler" / "forms-data.js"


def render() -> str:
    data = {slug: {"name": name, "entries": forms.schema(slug)} for slug, name in outputs.FORM_OUTPUTS}
    body = json.dumps(data, indent=1, ensure_ascii=False)
    return ("// Generated by scripts/build_clio_forms.py from app/forms.py. Do not edit by hand.\n"
            "(function (root) {\n"
            f"  root.MWB_FORMS = {body.replace(chr(10), chr(10) + '  ')};\n"
            "  if (typeof module !== \"undefined\") { module.exports = root.MWB_FORMS; }\n"
            "})(typeof window !== \"undefined\" ? window : globalThis);\n")


def main() -> int:
    TARGET.parent.mkdir(exist_ok=True)
    TARGET.write_text(render(), encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
